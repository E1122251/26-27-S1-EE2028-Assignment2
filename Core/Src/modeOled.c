static void OLED_WriteCmd(uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, 2, 100);
}

static void OLED_WriteData(uint8_t data) {
    uint8_t buf[2] = {0x40, data};
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, 2, 100);
}

static void OLED_SetCursor(uint8_t page, uint8_t col) {
    OLED_WriteCmd(0xB0 + page);
    OLED_WriteCmd(0x00 + (col & 0x0F));
    OLED_WriteCmd(0x10 + ((col >> 4) & 0x0F));
}

static void OLED_PutChar(char c) {
    if (c < 32 || c > 93) c = 32;
    uint16_t idx = (c - 32) * 5;
    for (uint8_t i = 0; i < 5; i++) {
        OLED_WriteData(Font5x7[idx + i]);
    }
    OLED_WriteData(0x00);
}

static void OLED_PrintStr(uint8_t page, uint8_t col, const char *str) {
    OLED_SetCursor(page, col);
    while (*str) {
        OLED_PutChar(*str++);
    }
}

void MOL_Init(void) {
    OLED_I2C1_LowLevelInit();
    OLED_WriteCmd(0xAE);
    OLED_WriteCmd(0xD5); OLED_WriteCmd(0x80);
    OLED_WriteCmd(0xA8); OLED_WriteCmd(0x3F);
    OLED_WriteCmd(0xD3); OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x40);
    OLED_WriteCmd(0x8D); OLED_WriteCmd(0x14);
    OLED_WriteCmd(0x20); OLED_WriteCmd(0x00);
    OLED_WriteCmd(0xA1);
    OLED_WriteCmd(0xC8);
    OLED_WriteCmd(0xDA); OLED_WriteCmd(0x12);
    OLED_WriteCmd(0x81); OLED_WriteCmd(0xCF);
    OLED_WriteCmd(0xD9); OLED_WriteCmd(0xF1);
    OLED_WriteCmd(0xDB); OLED_WriteCmd(0x40);
    OLED_WriteCmd(0xA4);
    OLED_WriteCmd(0xA6);
    MOL_PowerOff();
}

void MOL_Clear(void) {
    for (uint8_t p = 0; p < 8; p++) {
        OLED_SetCursor(p, 0);
        for (uint8_t c = 0; c < 128; c++) {
            OLED_WriteData(0x00);
        }
    }
}

void MOL_PowerOff(void) {
    MOL_Clear();
    OLED_WriteCmd(0xAE);
}

void MOL_PowerOn(void) {
    OLED_WriteCmd(0xAF);
}

void MOL_UpdateBattleScreen(int health, int energy, bool temp_warning) {
    char line1[25];
    char line2[25];
    OLED_PrintStr(0, 0, "=== BATTLE MODE ===");
    snprintf(line1, sizeof(line1), "Laser: %d/10  ", energy);
    OLED_PrintStr(2, 0, line1);
    snprintf(line2, sizeof(line2), "Hull: %d%%  ", health);
    OLED_PrintStr(4, 0, line2);
    if (temp_warning) {
        OLED_PrintStr(6, 0, "! OVERHEAT WARNING !");
    } else {
        OLED_PrintStr(6, 0, "                    ");
    }
}
